#!/usr/bin/env python3
"""Regenerate docs/action-reference.md from the action registry (developer tool).

    python3 tools/gen_action_table.py            write docs/action-reference.md
    python3 tools/gen_action_table.py --check    exit 1 if the file on disk differs (use in CI)

The text comes from netgen.campaign.actions (titles, tactics, techniques, protocols, parameters) and
netgen.campaign.actions.meta (the plain-language description), so it cannot drift from the code.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from netgen.campaign import actions, attack          # noqa: E402 - sys.path is set up before the import
from netgen.campaign.actions import meta             # noqa: E402 - sys.path is set up before the import

OUT = os.path.join(ROOT, "docs", "action-reference.md")


def _cell(text):
    return " ".join(str(text or "").split()).replace("|", "\\|")


def render():
    reg = actions.load_all()
    by = {}
    for _tok, spec in reg.items():
        by.setdefault(spec.tactic, []).append(spec)
    order = [t["slug"] for t in attack.tactics()]
    order += sorted(k for k in by if k not in order)
    lines = ["# Campaign action reference", "",
             "Generated by `dev/tools/gen_action_table.py` from the action registry. Do not edit by hand.", "",
             "%d actions in %d ATT&CK tactics. Every action emits real, checksum-valid packets from inert "
             "content; none carries exploit code." % (len(reg), len(by)), ""]
    for slug in order:
        specs = sorted(by.get(slug, []), key=lambda s: s.token)
        if not specs:
            continue
        tac = attack.tactic(slug) or {"name": slug}
        lines += ["## %s (%d)" % (tac["name"], len(specs)), "",
                  "| Action | What it does | Techniques | Protocols | Parameters |",
                  "|---|---|---|---|---|"]
        for s in specs:
            rec = meta.get(s.token) or {}
            plain = rec.get("plain") or s.summary
            params = ", ".join("`%s`" % p for p in s.params) or "none"
            lines.append("| `%s` %s | %s | %s | %s | %s |" % (
                s.token, _cell(s.title), _cell(plain), _cell(", ".join(s.techniques)),
                _cell(", ".join(s.protocols)), params))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""  # noqa: SIM115 handle outlives this scope
        if cur != text:
            print("docs/action-reference.md is out of date; run tools/gen_action_table.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
