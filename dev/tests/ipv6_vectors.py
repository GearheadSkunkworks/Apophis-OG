"""Hand-built IPv6 golden frames for the independent checker tests. Test code only: this is NOT
the engine builder and shares nothing with netgen. Frames are deterministic so the committed
fixtures/ipv6_golden.cap can be regenerated byte for byte (python3 -m tests.ipv6_vectors)."""
import os
import struct

FIXTURE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "ipv6_golden.cap")
MAC_A, MAC_B = bytes.fromhex("020000000001"), bytes.fromhex("020000000002")
A = bytes.fromhex("20010db8000000000000000000000001")
B = bytes.fromhex("20010db8000000000000000000000002")
LL_A = bytes.fromhex("fe800000000000000000000000000001")
ALL_NODES = bytes.fromhex("ff020000000000000000000000000001")
ALL_ROUTERS = bytes.fromhex("ff020000000000000000000000000002")


def csum(data):
    if len(data) & 1:
        data += b"\0"
    s = sum(struct.unpack("!%dH" % (len(data) // 2), data))
    while s >> 16:
        s = (s & 0xFFFF) + (s >> 16)
    return (~s) & 0xFFFF


def mcast_mac(dst):
    return b"\x33\x33" + dst[12:16]


def frame(src, dst, nh, seg, hop=64, dmac=MAC_B, smac=MAC_A, plen=None):
    plen = len(seg) if plen is None else plen
    ip = struct.pack("!IHBB", 0x60000000, plen, nh, hop) + src + dst
    return dmac + smac + b"\x86\xdd" + ip + seg


def with_csum(src, dst, nh, seg, at):
    """seg with its checksum (at byte offset `at`) filled over the 40-byte pseudo-header."""
    seg = seg[:at] + b"\0\0" + seg[at + 2:]
    c = csum(src + dst + struct.pack("!IBBBB", len(seg), 0, 0, 0, nh) + seg)
    return seg[:at] + struct.pack("!H", c) + seg[at + 2:]


def tcp(src=A, dst=B, **kw):
    seg = struct.pack("!HHIIBBHHH", 40000, 443, 1, 0, 5 << 4, 0x02, 65535, 0, 0) + b""
    return frame(src, dst, 6, with_csum(src, dst, 6, seg, 16), **kw)


def udp(src=A, dst=B, payload=b"hello", **kw):
    seg = struct.pack("!HHHH", 5353, 53, 8 + len(payload), 0) + payload
    return frame(src, dst, 17, with_csum(src, dst, 17, seg, 6), **kw)


def echo(src=A, dst=B, **kw):
    seg = struct.pack("!BBHHH", 128, 0, 0, 1, 1) + b"abcd"
    return frame(src, dst, 58, with_csum(src, dst, 58, seg, 2), **kw)


def solicited(target):
    return bytes.fromhex("ff0200000000000000000001ff") + target[13:]


def ns(target=B, src=LL_A, opt=None):
    """Neighbor Solicitation for `target` to its solicited-node address, with a source link-layer option."""
    dst = solicited(target)
    opt = opt if opt is not None else b"\x01\x01" + MAC_A
    seg = struct.pack("!BBHI", 135, 0, 0, 0) + target + opt
    return frame(src, dst, 58, with_csum(src, dst, 58, seg, 2), hop=255, dmac=mcast_mac(dst))


def na(src=B, dst=LL_A):
    seg = struct.pack("!BBHI", 136, 0, 0, 0x60000000) + src + b"\x02\x01" + MAC_B
    return frame(src, dst, 58, with_csum(src, dst, 58, seg, 2), hop=255, dmac=MAC_A, smac=MAC_B)


def rs(src=LL_A):
    seg = struct.pack("!BBHI", 133, 0, 0, 0) + b"\x01\x01" + MAC_A
    return frame(src, ALL_ROUTERS, 58, with_csum(src, ALL_ROUTERS, 58, seg, 2), hop=255,
                 dmac=mcast_mac(ALL_ROUTERS))


def ra(src=bytes.fromhex("fe80000000000000000000000000000f")):
    seg = struct.pack("!BBHBBHII", 134, 0, 0, 64, 0, 1800, 0, 0) \
        + b"\x01\x01" + MAC_B + b"\x05\x01\x00\x00" + struct.pack("!I", 1500)
    return frame(src, ALL_NODES, 58, with_csum(src, ALL_NODES, 58, seg, 2), hop=255,
                 dmac=mcast_mac(ALL_NODES), smac=MAC_B)


def golden():
    return [tcp(), udp(), echo(), ns(), na(), rs(), ra()]


def pcap_bytes(frames):
    out = struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 1)
    for i, f in enumerate(frames):
        out += struct.pack("<IIII", 1700000000 + i, 0, len(f), len(f)) + f
    return out


def write_pcap(path, frames):
    with open(path, "wb") as fh:
        fh.write(pcap_bytes(frames))


if __name__ == "__main__":
    write_pcap(FIXTURE, golden())
    print("wrote", FIXTURE)
