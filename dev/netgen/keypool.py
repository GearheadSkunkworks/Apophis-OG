"""RSA-2048 key source that generates ahead on spare cores.

Key generation is about half of a default build and OpenSSL releases the GIL, so a few
background threads keep a short buffer of finished keys. Keys still come from OpenSSL (never
the seeded RNG), have the same size, and each is handed out exactly once, so they stay unique
per host. With no key ready, next_key() generates one inline, as the old call sites did."""
import os
import threading
from collections import deque

from cryptography.hazmat.primitives.asymmetric import rsa

AHEAD = 8                       # finished-or-in-flight keys kept ahead of demand
_cv = threading.Condition()
_ready = deque()
_busy = 0                       # keys currently being generated by workers
_started = False


def _gen():
    return rsa.generate_private_key(65537, 2048)


def _worker():
    global _busy
    while True:
        with _cv:
            while len(_ready) + _busy >= AHEAD:
                _cv.wait()
            _busy += 1
        try:
            key = _gen()
        except BaseException:
            with _cv:
                _busy -= 1
            raise
        with _cv:
            _busy -= 1
            _ready.append(key)
            _cv.notify_all()


def _start():
    global _started
    for _ in range(max(1, min(8, (os.cpu_count() or 1) - 1))):
        threading.Thread(target=_worker, name="keypool", daemon=True).start()
    _started = True


def next_key():
    with _cv:
        if not _started:
            _start()
        key = _ready.popleft() if _ready else None
        _cv.notify_all()
    return key if key is not None else _gen()
